export type DictKey = keyof typeof DICT;

export function translate(locale: Loc, key: DictKey): string {
  const e = DICT[key] as Entry;
  return (locale === "kk" ? e.kk : locale === "en" ? e.en : e.ru) ?? e.ru;
}

/** Переводимое поле данных (I18n Json): локаль → ru → en → первое значение. */
export function trJson(locale: Loc, value: unknown): string {
  if (value == null) return "";
  if (typeof value === "string") return value;
  const v = value as Record<string, string | undefined>;
  return v[locale] || v.ru || v.en || Object.values(v).find(Boolean) || "";
}
